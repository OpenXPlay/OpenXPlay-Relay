package org.openxplay.direlay.logs

import com.google.zxing.BarcodeFormat
import com.google.zxing.EncodeHintType
import com.google.zxing.qrcode.QRCodeWriter
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel

object LogQrCode {
    // No CHARACTER_SET hint: the link is ASCII, and a UTF-8 hint adds an ECI header some scanners mishandle.
    fun matrix(link: String) = QRCodeWriter().encode(link, BarcodeFormat.QR_CODE, 0, 0,
        mapOf(EncodeHintType.ERROR_CORRECTION to ErrorCorrectionLevel.M, EncodeHintType.MARGIN to 2))
}
